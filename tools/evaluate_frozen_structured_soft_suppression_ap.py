#!/usr/bin/env python3
"""Run one frozen class-agnostic AP for a no-GT soft-suppression plan.

The preflight verifies scene isolation, the official100 soft-suppression
result, model and candidate-input digests, complete component coverage, and
candidate-retention invariants.  The AP aggregator is then called exactly
once for the frozen soft-suppression scores.  Candidate files are never
modified.
"""
